  /// The handle without the '@' the field shows.
  ///
  /// The field is seeded with '@' as a visual prefix, but the backend stores and
  /// validates the bare handle — sending the decoration would fail its format rules.
  String _handle() =>
      _model.usernameTextController.text.replaceAll('@', '').trim();

  /// Asks the backend whether the handle is free and correctly formed.
  ///
  /// The local check only catches the obvious, and cannot know what is taken. The
  /// backend returns which rules were broken, so the field can say what is actually
  /// wrong instead of going quiet.
  Future<void> _checkHandle() async {
    final handle = _handle();

    if (handle.length < 2) {
      safeSetState(() {
        _model.isValidUser = false;
        _model.isAvailable = null;
        _model.unavailableReason = null;
      });
      return;
    }

    safeSetState(() => _model.isChecking = true);

    final result = await AuthSession.instance.api.checkUsername(handle);

    if (!mounted) return;

    safeSetState(() {
      _model.isChecking = false;

      switch (result) {
        case ApiSuccess<UsernameCheck>(:final value):
          _model.isAvailable = value.available;
          _model.isValidUser = value.available;
          _model.unavailableReason = value.available
              ? null
              : (value.unmet.isEmpty
                  ? 'That handle is already taken.'
                  : _describe(value.unmet));
        case ApiFailure<UsernameCheck>():
        case ApiUnreachable<UsernameCheck>():
          // Could not find out. The button stays disabled rather than letting the user
          // commit to a handle that may be refused a moment later.
          _model.isAvailable = null;
          _model.isValidUser = false;
          _model.unavailableReason = result.messageIn(
            AuthSession.instance.languageCode,
          );
      }
    });
  }

  /// Turns the backend's rule names into something worth reading.
  ///
  /// The names are stable identifiers meant for a client to map; showing them raw
  /// would put 'no-leading-digit' in front of a merchant.
  static String _describe(List<String> unmet) {
    const wording = <String, String>{
      'length': 'Use between 3 and 30 characters.',
      'start': 'Start with a letter.',
      'characters': 'Letters, numbers, dots and underscores only.',
      'separator': 'No two dots or underscores in a row.',
      'trailing': 'Cannot end with a dot or underscore.',
      'reserved': 'That handle is reserved.',
    };

    for (final rule in unmet) {
      final described = wording[rule];
      if (described != null) return described;
    }

    return 'That handle cannot be used.';
  }

